"""The image, the locks and CI agree on one Python: the one of the base image."""

import os
import re
import shutil
import subprocess
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = re.compile(r"^FROM (python:(\d+\.\d+)\.\d+-slim@sha256:[0-9a-f]{64})(?: AS \w+)?$", re.M)


def _lock_outputs(root: Path = ROOT, **env: str) -> dict[str, str]:
    environ = {k: v for k, v in os.environ.items() if k != "LOCK_PYTHON"} | env
    out = subprocess.run(
        ["bash", str(root / "scripts/lock.sh"), "outputs"],
        capture_output=True,
        text=True,
        check=True,
        env=environ,
    ).stdout
    return dict(line.split("=", 1) for line in out.splitlines())


def _lock_default(name: str) -> str:
    script = (ROOT / "scripts/lock.sh").read_text()
    match = re.search(rf'^: "\${{{name}:=([^}}]*)}}"$', script, re.M)
    assert match, f"scripts/lock.sh sets no default for {name}"
    return match.group(1)


def test_both_stages_build_on_one_base_image_pinned_by_digest() -> None:
    dockerfile = (ROOT / "Dockerfile").read_text()
    froms = re.findall(r"^FROM .*$", dockerfile, re.M)
    bases = {BASE.fullmatch(f).group(1) for f in froms if BASE.fullmatch(f)}
    assert len(froms) == 2 and len(bases) == 1, froms
    assert "ARG PYTHON_VERSION" not in dockerfile


def test_the_locks_are_compiled_on_the_python_of_the_base_image() -> None:
    python = BASE.search((ROOT / "Dockerfile").read_text()).group(2)
    assert _lock_outputs()["python"] == python
    assert _lock_outputs(LOCK_PYTHON="3.99")["python"] == "3.99"
    for lock in ("image", "dev"):
        header = (ROOT / f"requirements/{lock}.txt").read_text()
        assert f"autogenerated by pip-compile with Python {python}\n" in header, lock


def test_the_checks_run_on_every_python_the_package_declares() -> None:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    declared = [
        c.rsplit(" :: ", 1)[1]
        for c in project["classifiers"]
        if re.fullmatch(r"Programming Language :: Python :: 3\.\d+", c)
    ]
    assert _lock_default("CHECK_PYTHONS").split() == declared
    assert project["requires-python"] == f">={declared[0]}"
    assert _lock_outputs()["python"] in declared


def test_the_image_installs_the_lock_with_its_hashes_and_nothing_else() -> None:
    dockerfile = (ROOT / "Dockerfile").read_text()
    lock = dockerfile.index("--require-hashes -r /tmp/requirements/image.txt")
    core = dockerfile.index("--no-deps /tmp/akko_mcp_trino-*.whl")
    check = dockerfile.index("&& pip check")
    atlas = dockerfile.index("--no-deps /tmp/akko_mcp_trino_atlas-*.whl")
    # The check sees the core and its lock only: the provider requires a newer core.
    assert lock < core < check < atlas
    assert dockerfile.count("pip install") == 4  # build, then the lock and the two wheels


def _release_image(tag: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["bash", str(ROOT / "scripts/release-image.sh"), str(tag)],
        capture_output=True,
        text=True,
    )


def test_the_release_reads_the_platforms_of_a_tag_with_the_locks(tmp_path: Path) -> None:
    for name in ("Dockerfile", "scripts/lock.sh", "requirements/image.txt"):
        (tmp_path / name).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(ROOT / name, tmp_path / name)
    script = tmp_path / "scripts/lock.sh"
    script.write_text(script.read_text().replace("linux/amd64,linux/arm64", "linux/s390x"))
    done = _release_image(tmp_path)
    assert done.returncode == 0, done.stderr
    assert done.stdout == "platforms=linux/s390x\n"
    assert done.stderr == ""


def test_the_release_of_a_tag_before_the_locks_uses_its_own_requirements(tmp_path: Path) -> None:
    (tmp_path / "image-requirements.txt").write_text("mcp==2.2.0\n")
    done = _release_image(tmp_path)
    assert done.returncode == 0, done.stderr
    assert done.stdout == f"platforms={_lock_outputs()['platforms']}\n"
    assert "image-requirements.txt" in done.stderr


def test_the_release_refuses_a_tag_with_neither(tmp_path: Path) -> None:
    done = _release_image(tmp_path)
    assert done.returncode == 1
    assert done.stdout == ""
    assert "neither" in done.stderr
