BASE = re.compile(r"^FROM (python:(\d+\.\d+)\.\d+-slim@sha256:[0-9a-f]{64})(?: AS \w+)?$", re.M)


def _lock_outputs(root: Path = ROOT, **env: str) -> dict[str, str]:
    environ = {k: v for k, v in os.environ.items() if k != "LOCK_PYTHON"} | env
    out = subprocess.run(
        ["bash", str(root / "scripts/lock.sh"), "outputs"],
        capture_output=True,
        text=True,
        check=True,
        env=environ,
    ).stdout
    return dict(line.split("=", 1) for line in out.splitlines())


def _lock_default(name: str) -> str:
    script = (ROOT / "scripts/lock.sh").read_text()
    match = re.search(rf'^: "\${{{name}:=([^}}]*)}}"$', script, re.M)
    assert match, f"scripts/lock.sh sets no default for {name}"
    return match.group(1)


